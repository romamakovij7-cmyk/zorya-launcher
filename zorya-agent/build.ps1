# Сборка Java-агента Eternal Cosmetics: build\agent\eternal-agent.jar (малый) и eternal-core.jar (с ASM внутри).
# Нужен JDK 17+ (компилируем под Java 8, чтобы работало на любой Java игры) и ASM (берём тот, что лаунчер уже скачал для Fabric).
# Запуск:  powershell -ExecutionPolicy Bypass -File eternal-agent\build.ps1
param(
  [string]$Jdk = 'C:\Program Files\Eclipse Adoptium\jdk-25.0.4.7-hotspot',
  [string]$Asm = "$env:APPDATA\EternalLauncher\meta\libraries\org\ow2\asm\asm\9.10.1\asm-9.10.1.jar"
)
$ErrorActionPreference = 'Stop'
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$root = Split-Path -Parent $here
$javac = Join-Path $Jdk 'bin\javac.exe'
$jar = Join-Path $Jdk 'bin\jar.exe'
if (-not (Test-Path $javac)) { throw "javac не найден: $javac" }
if (-not (Test-Path $Asm)) { throw "ASM не найден: $Asm" }

$out = Join-Path $here 'out'
$dest = Join-Path $root 'build\agent'
if (Test-Path $out) { Remove-Item $out -Recurse -Force }
New-Item -ItemType Directory $out, $dest -Force | Out-Null
$agentClasses = Join-Path $out 'agent'
$coreClasses = Join-Path $out 'core'
New-Item -ItemType Directory $agentClasses, $coreClasses | Out-Null

# 1) агент: только точка входа
$agentSrc = @(Get-ChildItem "$here\src\eternal\agent\*.java" | ForEach-Object { $_.FullName })
& $javac --release 8 -Xlint:-options -encoding UTF-8 -d $agentClasses $agentSrc
if ($LASTEXITCODE -ne 0) { throw 'javac (agent) failed' }
$manifest = Join-Path $out 'agent.mf'
[IO.File]::WriteAllText($manifest, "Premain-Class: eternal.agent.EternalAgent`nCan-Redefine-Classes: false`nCan-Retransform-Classes: false`n", (New-Object Text.UTF8Encoding($false)))
& $jar --create --file (Join-Path $dest 'eternal-agent.jar') --manifest $manifest -C $agentClasses .
if ($LASTEXITCODE -ne 0) { throw 'jar (agent) failed' }

# 2a) картинки сердечек (eternal-agent\hearts-src\heart_N.png) уходят внутрь ядра как данные, а не лежат файлами в папке игры;
# слегка зашифрованы (это не защита, а чтобы их не вытащить простым просмотром файла)
$genDir = Join-Path $out 'gen\eternal\core'
New-Item -ItemType Directory $genDir -Force | Out-Null
$key = [byte[]](0x5A, 0x13, 0xC7, 0x2E, 0x91, 0x68, 0xB4, 0x0D, 0xE3, 0x7F, 0x26, 0xA9, 0x4C, 0xD0, 0x85, 0x3B)
$frames = foreach ($i in 0..5) {
  $bytes = [IO.File]::ReadAllBytes((Join-Path $root "eternal-agent\hearts-src\heart_$i.png"))
  for ($k = 0; $k -lt $bytes.Length; $k++) { $bytes[$k] = $bytes[$k] -bxor $key[$k % $key.Length] }
  '        "' + [Convert]::ToBase64String($bytes) + '"'
}
$keyList = ($key | ForEach-Object { '(byte) ' + $_ }) -join ', '
$java = "package eternal.core;`n`n/** Generated by build.ps1: the heart pictures (masked). */`nfinal class HeartData {`n    static final byte[] KEY = {$keyList};`n    static final String[] FRAMES = {`n" + ($frames -join ",`n") + "`n    };`n`n    private HeartData() { }`n}`n"
[IO.File]::WriteAllText((Join-Path $genDir 'HeartData.java'), $java, (New-Object Text.UTF8Encoding($false)))

# 2) ядро: наши классы + ASM
$coreSrc = @(Get-ChildItem "$here\src\eternal\core\*.java" | ForEach-Object { $_.FullName }) + @((Join-Path $genDir 'HeartData.java'))
& $javac --release 8 -Xlint:-options -encoding UTF-8 -cp "$Asm;$agentClasses" -d $coreClasses $coreSrc
if ($LASTEXITCODE -ne 0) { throw 'javac (core) failed' }
Push-Location $coreClasses
try { & $jar xf $Asm org } finally { Pop-Location }
& $jar --create --file (Join-Path $dest 'eternal-core.jar') -C $coreClasses .
if ($LASTEXITCODE -ne 0) { throw 'jar (core) failed' }

foreach ($f in 'eternal-agent.jar', 'eternal-core.jar') {
  $p = Join-Path $dest $f
  '{0,-20} {1,8:N0} B   sha256 {2}' -f $f, (Get-Item $p).Length, (Get-FileHash $p -Algorithm SHA256).Hash.Substring(0, 16)
}
